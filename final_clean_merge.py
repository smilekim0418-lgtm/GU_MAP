import json
import shutil
import os
import math
from shapely.geometry import Polygon
from shapely.ops import unary_union

def distance(p1, p2):
    return math.hypot(p1[0] - p2[0], p1[1] - p2[1])

def add_holes_to_exterior(exterior, holes):
    if exterior[0] == exterior[-1]: exterior = exterior[:-1]
    for hole in holes:
        if hole[0] == hole[-1]: hole = hole[:-1]
        min_dist = float("inf")
        best_e = 0
        best_h = 0
        for i, ep in enumerate(exterior):
            for j, hp in enumerate(hole):
                d = distance(ep, hp)
                if d < min_dist:
                    min_dist = d
                    best_e = i
                    best_h = j
        hole = hole[best_h:] + hole[:best_h]
        exterior = exterior[:best_e+1] + hole + [hole[0]] + exterior[best_e:]
    return exterior

floors = ['2F', '3F', '4F', '5F']
work_dir = r'GUMAP-개발\floorplan\work'

for floor in floors:
    # Use current json for 2F, original backup for 3,4,5F
    if floor == '2F':
        fpath = os.path.join(work_dir, f'{floor}_labeled.json')
    else:
        fpath = os.path.join(work_dir, f'{floor}_labeled_backup_corridor.json')
        
    if not os.path.exists(fpath): continue
    
    with open(fpath, 'r', encoding='utf-8') as f:
        data = json.load(f)
        
    corridors = [p for p in data['polygons'] if p.get('type') == 'corridor']
    others = [p for p in data['polygons'] if p.get('type') != 'corridor']
    if not corridors: continue
    
    c_polys = []
    for c in corridors:
        pts = c['points']
        if len(pts) >= 3:
            p = Polygon(pts)
            if not p.is_valid: p = p.buffer(0)
            c_polys.append(p)
            
    if not c_polys: continue
    merged_c = unary_union(c_polys)
    
    # Optional: slightly simplify to remove colinear points generated by merging overlapping rectangles
    # buffer(0) or simplify(0.1) removes microscopic floating point vertices
    merged_c = merged_c.simplify(0.5, preserve_topology=True)
        
    merged_recs = []
    def process_poly(poly):
        if poly.area < 100: return
        ext = list(poly.exterior.coords)
        holes = [list(interior.coords) for interior in poly.interiors]
        
        if holes:
            ext = add_holes_to_exterior(ext, holes)
        else:
            if ext[0] == ext[-1]: ext = ext[:-1]
                
        pts = [[round(x), round(y)] for x, y in ext]
        
        # Deduplicate sequential identical points
        dedup_pts = []
        for p in pts:
            if not dedup_pts or p != dedup_pts[-1]:
                dedup_pts.append(p)
        if len(dedup_pts) > 1 and dedup_pts[0] == dedup_pts[-1]:
            dedup_pts = dedup_pts[:-1]
            
        if len(dedup_pts) < 3: return
            
        merged_recs.append({
            'points': dedup_pts,
            'area_px': poly.area,
            'centroid': [round(poly.centroid.x), round(poly.centroid.y)],
            'room_id': '복도',
            'type': 'corridor',
            'candidates': []
        })

    if merged_c.geom_type == 'Polygon':
        process_poly(merged_c)
    elif merged_c.geom_type == 'MultiPolygon':
        for p in merged_c.geoms:
            process_poly(p)
    elif merged_c.geom_type == 'GeometryCollection':
        for p in merged_c.geoms:
            if p.geom_type == 'Polygon': process_poly(p)
            
    data['polygons'] = others + merged_recs
    
    out_path = os.path.join(work_dir, f'{floor}_labeled.json')
    with open(out_path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        
    print(f'{floor}: Merged {len(corridors)} original boxes into {len(merged_recs)} clean polygons with holes preserved.')
